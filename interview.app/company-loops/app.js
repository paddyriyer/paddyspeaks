      if (e.key === "Tab" && !e.shiftKey) { e.preventDefault(); code.setRangeText("    ", code.selectionStart, code.selectionEnd, "end"); a.code = code.value; save(); }
      if (e.key === "Enter" && (e.ctrlKey || e.metaKey)) { e.preventDefault(); runCheck(it, tpl, ins); }
