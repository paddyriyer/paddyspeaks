const sec = (title, html) => (html ? `<div class="cl-sec-h">${esc(title)}</div><div class="cl-body">${html}</div>` : "");
function msgHTML(m, F) {
  const who = m.role === "you" ? "You" : m.role === "incident" ? "Production Reality Check" : m.role === "clar" ? "Interviewer (clarification)" : "Interviewer";
  const cls = m.role === "you" ? "you" : m.role === "incident" ? "inc" : "int";
  return `<div class="cl-msg ${cls}"><span class="who">${who}${m.note ? " · " + esc(m.note) : ""}</span>${m.role === "you" ? esc(m.text) : F(m.html)}</div>`;
}
function runnableNote(kind) {
  const s = state.settings;
  if (kind === "sql" && s.dialect !== "postgresql") return `<p class="cl-banner warn">You chose ${esc(label("dialects", s.dialect))}. The checker runs PostgreSQL: write PostgreSQL to check your result, or answer in your dialect and score it yourself against the reference's dialect notes.</p>`;
  if ((kind === "python" || kind === "debug") && s.language !== "python") return `<p class="cl-banner warn">You chose ${esc(label("languages", s.language))}. Only Python runs in the browser: answer in ${esc(label("languages", s.language))} and score it yourself, or switch to Python to run the tests.</p>`;
  return "";
}

function tableHTML(t, max = 40) {
  return `<div class="cl-table cl-data"><table><thead><tr>${t.columns.map((c) => `<th>${esc(c)}</th>`).join("")}</tr></thead><tbody>` +
    t.rows.slice(0, max).map((r) => "<tr>" + r.map((x) => `<td>${x === null ? '<span class="cl-muted">NULL</span>' : esc(x)}</td>`).join("") + "</tr>").join("") +
    (t.rows.length > max ? `<tr><td colspan="${t.columns.length}" class="cl-muted">… ${t.rows.length - max} more rows (all loaded in the checker)</td></tr>` : "") + "</tbody></table></div>";
}
function dataHTML(tpl, ins) {
  if (!ins.inst) return "";
  const x = ins.inst;
  if (tpl.kind === "sql") {
    return `<div class="cl-sec-h">Tables</div>` + x.tables.map((t) => `<p class="cl-small"><code>${esc(t.name)}</code></p>` + tableHTML(t)).join("") +
      `<details><summary class="cl-small">Show the table definitions (SQL)</summary><div class="cl-body"><pre><code>${esc(x.setup.split("INSERT INTO")[0])}</code></pre></div></details>` +
      `<div class="cl-sec-h">Expected output</div>` + tableHTML(x.expected);
  }
  const m = ins.mod;
  return `<div class="cl-sec-h">Signature</div><div class="cl-body"><pre><code>${esc(m.signature)}</code></pre></div>` +
    `<div class="cl-sec-h">Examples</div><div class="cl-body">` + (x.samples || []).map((s) => `<pre><code>${esc(m.entry)}${esc(s.args.length > 600 ? s.args.slice(0, 600) + " …" : s.args)}\n→ ${esc(s.expect)}</code></pre>`).join("") + "</div>";
}
