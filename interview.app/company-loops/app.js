function checkLine(it) {
  if (!it.checks) return "";
  return `<div class="cl-banner ${it.checks.passed === it.checks.total ? "good" : "warn"}">Last check: ${it.checks.passed} of ${it.checks.total} passed.</div>`;
}
function answerText(it) {
  const a = it.answer;
  return [a.code, a.notes, ...Object.values(a.fields || {}), ...it.convo.filter((m) => m.role === "you").map((m) => m.text)].filter(Boolean).join("\n");
}

