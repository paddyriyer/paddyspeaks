/* ------------------------------------------------------------ instances */

function paramValues(spec, level) {
  if (Array.isArray(spec)) return spec;
  for (const l of [level, 2, 3, 1]) if (spec[String(l)]) return spec[String(l)];
  return Object.values(spec)[0];
}
function levelFor(tpl, wanted) {
  if (tpl.levels.includes(wanted)) return wanted;
  return tpl.levels.reduce((a, b) => (Math.abs(b - wanted) < Math.abs(a - wanted) ? b : a));
}

/* An instance is (template, seed, level). Executable templates regenerate their
   data from the seed; text templates pick one value per parameter. Nothing large
   is stored: resuming a session regenerates the same instance. */
async function instance(tpl, seed, level) {
  if (tpl.generator) {
    const mod = await generator(tpl.generator);
    const inst = mod.generate(makeRng(seed), level);
    return { mod, inst, vars: inst.vars || {}, key: `${tpl.id}:${seed}:${level}` };
  }
  const r = makeRng(seed);
  const vars = {};
  const idx = [];
  for (const [name, spec] of Object.entries(tpl.params || {})) {
    const vals = paramValues(spec, level);
    const k = Math.floor(r.next() * vals.length);
    vars[name] = vals[k];
    idx.push(k);
  }
  return { mod: null, inst: null, vars, key: `${tpl.id}:${level}:${idx.join(".")}` };
}

async function freshSeed(tpl, level) {
  const seen = new Set(state.seen[tpl.id] || []);
  let best = null;
  for (let tries = 0; tries < 30; tries++) {
    const seed = 1 + Math.floor(Math.random() * 2_000_000_000);
    const { key } = await instance(tpl, seed, level);
    if (!seen.has(key)) return seed;
    best = best ?? seed;
  }
  return best;   // every variant seen: reuse one rather than fail
}
function markSeen(tid, key) {
  const a = (state.seen[tid] = state.seen[tid] || []);
  if (!a.includes(key)) a.push(key);
  if (a.length > 200) a.splice(0, a.length - 200);
}

/* Choose a template for a loop: role match first, least used next, then random. */
async function pickTemplate(companyId, loop, exclude = new Set(), preferCompetency = null) {
  const data = await companyData(companyId);
  const pool = data.templates.filter((t) => t.loop === loop && !exclude.has(t.id));
  if (!pool.length) return null;
  const role = state.settings.role;
  const score = (t) => {
    let s = Math.random();
    if (t.roles.includes(role)) s += 4;
    s -= Math.min(3, (state.seen[t.id] || []).length * 1.5);
    if (preferCompetency && kindGroup(t.kind) === preferCompetency) s += 5;
    return s;
  };
  return pool.sort((a, b) => score(b) - score(a))[0];
}

function wantedLevel(prev) {
  const d = cfg().difficulty.find((x) => x.id === state.settings.difficulty);
  if (d && d.level) return d.level;
  // Adaptive: start at the seniority's level, move with the last self-score.
  let lvl = seniority().level;
  if (prev && prev.avg != null) lvl = prev.avg >= 3 ? Math.min(3, prev.level + 1) : prev.avg <= 1.5 ? Math.max(1, prev.level - 1) : prev.level;
  return lvl;
}

/* ------------------------------------------------------------ sessions */

function newId() { return "s" + Date.now().toString(36) + Math.floor(Math.random() * 1e6).toString(36); }

async function startSession(modeOverride) {
  const s = state.settings;
  const mode = modeOverride || s.mode;
  const loops = mode === "assessment" ? [1, 2, 3, 4, 5] : s.loops.slice().sort();
  const items = [];
  const used = new Set();
  const companies = available().map((c) => c.id);
  if (mode === "weak") {
    const weak = weakAreas();
    if (!weak.length) { toast("Weak-area practice needs at least one scored question. Practise or take a mock first."); return; }
    const pool = s.company && company(s.company)?.status === "available" ? [s.company] : companies;
    for (const w of weak.slice(0, 3)) {
      for (const loop of w.loops) {
        const co = pool[items.length % pool.length];
        const t = await pickTemplate(co, loop, used, w.group);
        if (t && kindGroup(t.kind) === w.group) { used.add(t.id); items.push(await newItem(co, t)); break; }
      }
    }
    if (!items.length) { toast("No new questions match your weakest areas yet."); return; }
  } else {
    const offset = Math.floor(Math.random() * companies.length);   // mixed: rotate through companies, one per loop
    for (const [k, loop] of loops.entries()) {
      const co = mode === "mixed" ? companies[(k + offset) % companies.length] : s.company;
      const t = await pickTemplate(co, loop, used);
      if (t) { used.add(t.id); items.push(await newItem(co, t)); }
    }
  }
  if (!items.length) { toast("No questions available for that selection."); return; }
  const minutes = items.reduce((a, it) => a + it.minutes, 0);
  state.session = {
    id: newId(), mode, created: Date.now(), settings: JSON.parse(JSON.stringify(s)), items, i: 0,
    deadline: mode === "assessment" ? Date.now() + minutes * 60000 : null, finished: null,
  };
  items[0].started = Date.now();
  save(true);
  location.hash = "#/interview";
}

async function newItem(co, t, prev) {
  const level = levelFor(t, wantedLevel(prev));
  const seed = await freshSeed(t, level);
  const minutes = Math.round(t.minutes * seniority().time);
  return { company: co, tid: t.id, loop: t.loop, kind: t.kind, topic: t.topic, title: t.title, seed, level, minutes,
    answer: {}, checks: null, convo: [], hints: 0, asked: [], fu: 0, incident: null, started: null, finished: null,
    scores: {}, revealed: false };
}

const kindGroup = (kind) => cfg().kind_competencies[kind];
const comps = (kind) => cfg().competencies[kindGroup(kind)];

function finishSession() {
  const s = state.session;
  if (!s) return;
  s.finished = s.finished || Date.now();
  s.items.forEach((it) => { if (!it.finished && it.started) it.finished = Date.now(); });
  if (!state.history.some((h) => h.id === s.id)) state.history.unshift(s);
  if (state.history.length > HISTORY_CAP) state.history.length = HISTORY_CAP;
  state.session = null;
  save(true);
  location.hash = "#/review/" + s.id;
}

