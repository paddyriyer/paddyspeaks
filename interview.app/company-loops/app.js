/* ---- the interviewer: deterministic rules first, then the scripted follow-ups ---- */

function submitTurn(it, tpl, ins, F, replyText) {
  const box = $("#convo");
  const first = !it.convo.some((m) => m.role === "you" && m.first);
  let text = "";
  if (first) {
    text = summarise(it) || "";
    if (!text.trim()) { toast("Write an answer first."); return; }
    it.convo.push({ role: "you", first: true, text: tpl.kind === "sql" || tpl.kind === "python" || tpl.kind === "debug" ? "(submitted code" + (it.answer.notes ? " and notes" : "") + ")" : "(submitted my answer)" });
  } else {
    text = (replyText || "").trim();
    if (!text) { toast("Write your reply first."); return; }
    it.convo.push({ role: "you", text });
    $("#reply").value = "";
  }
  const turn = nextTurn(it, tpl, ins, (answerText(it) + "\n" + text).toLowerCase());
  it.convo.push(turn);
  save(true);
  box.innerHTML = it.convo.map((m) => msgHTML(m, F)).join("");
  $("#submit").hidden = true;
  $("#reply-box").hidden = false;
  box.lastElementChild.scrollIntoView({ block: "nearest" });
}
function summarise(it) {
  const a = it.answer;
  return [a.code && a.code.trim() && !/^\s*(--.*\n)*\s*SELECT 1;\s*$/i.test(a.code) ? a.code : "", a.notes, ...Object.values(a.fields || {})].filter((x) => x && x.trim()).join("\n");
}
function nextTurn(it, tpl, ins, text) {
  const max = seniority().followups;
  // Production Reality Check: in loops 3 and 4, after the first follow-up.
  if ((tpl.loop === 3 || tpl.loop === 4) && it.incident === null && it.fu >= 1 && tpl.incidents.length) {
    it.incident = it.seed % tpl.incidents.length;
    return { role: "incident", html: tpl.incidents[it.incident] + "<br><em>Walk me through diagnosis, recovery, the trade-offs you accept, and how you prevent it.</em>" };
  }
  if (it.fu >= max) return { role: "int", html: "That is all I have on this one. Finish when you are ready, or keep refining your answer." };
  for (const [k, r] of tpl.rules.entries()) {
    if (it.asked.includes(k)) continue;
    const hit = r.when.find((w) => text.includes(w));
    if (hit) { it.asked.push(k); it.fu++; return { role: "int", html: r.ask, note: `reacting to “${hit}”` }; }
  }
  const nextFu = tpl.followups.findIndex((_, k) => !it.asked.includes("f" + k));
  if (nextFu >= 0) { it.asked.push("f" + nextFu); it.fu++; return { role: "int", html: tpl.followups[nextFu] }; }
  return { role: "int", html: "I have no further questions on this one." };
}
async function clarify(it, tpl, ins, F) {
  const inp = $("#clarify");
  const q = inp.value.trim();
  if (!q) return;
  inp.value = "";
  it.convo.push({ role: "you", text: "Q: " + q });
  const words = new Set((q.toLowerCase().match(/[a-z][a-z0-9_]+/g) || []).filter((w) => w.length >= 4));
  let best = null, bestN = 0;
  for (const c of tpl.clarifications) {
    const n = c.keywords.filter((k) => words.has(k) || [...words].some((w) => w.startsWith(k.slice(0, 5)) && k.length >= 5)).length;
    if (n > bestN) { best = c; bestN = n; }
  }
  if (best && bestN >= 1) it.convo.push({ role: "clar", html: best.a });
  else if (aiKey()) {
    try {
      const r = await callAI(
        "You are the interviewer in a simulated technical interview. Answer the candidate's clarifying question in one or two sentences, consistent with the scenario. If the scenario does not specify it, tell them to state an assumption and suggest a sensible one. Never reveal the solution.",
        "SCENARIO:\n" + plain(F(tpl.sections.scenario) + F(tpl.sections.problem) + F(tpl.sections.constraints)) + "\n\nQUESTION: " + q,
        { type: "object", properties: { answer: { type: "string" } }, required: ["answer"], additionalProperties: false });
      it.convo.push({ role: "clar", html: esc(r.answer), note: "AI" });
    } catch (e) { it.convo.push({ role: "clar", html: "The scenario does not say. State your assumption and carry on." }); }
  } else it.convo.push({ role: "clar", html: "The scenario does not say. State your assumption and carry on." });
  save(true);
  $("#convo").innerHTML = it.convo.map((m) => msgHTML(m, F)).join("");
}

/* ---- run & check ---- */

async function runCheck(it, tpl, ins) {
  const out = $("#out"), btn = $("#run");
  const code = $("#code").value;
  btn.disabled = true;
  out.innerHTML = '<p class="cl-muted">Running…</p>';
  try {
    const res = tpl.kind === "sql" ? await checkSQL(ins.inst, code) : await checkPython(it, tpl, ins, code);
    it.checks = { passed: res.passed, total: res.total, failed: res.failed || [], diag: res.diag || null, at: Date.now() };
    save();
    out.innerHTML = res.html;
  } catch (e) {
    out.innerHTML = `<div class="cl-banner bad">${esc(e.message || String(e))}</div>`;
  } finally { btn.disabled = false; }
}

let pgPromise = null;
function pg() {
  if (!pgPromise) {
    pgPromise = (async () => {
      const mod = await import("/interview.app/vendor/pglite/index.js");
      const PGlite = mod.PGlite || (mod.default && mod.default.PGlite) || mod.default;
      const asText = (x) => x;   // keep PostgreSQL's own text for dates, timestamps, numerics, int8, booleans
      return PGlite.create({ parsers: { 16: asText, 20: asText, 1082: asText, 1114: asText, 1184: asText, 1186: asText, 1700: asText } });
    })();
    pgPromise.catch(() => { pgPromise = null; });
  }
  return pgPromise;
}
async function checkSQL(x, sql) {
  const db = await pg();
  await db.exec("DISCARD ALL");
  await db.exec("DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public; SET search_path TO public; SET client_min_messages TO warning;");
  await db.exec(x.setup);
  let results;
  try { results = await db.exec(sql); } catch (e) { return { passed: 0, total: 1, failed: ["PostgreSQL error"], html: `<div class="cl-banner bad">PostgreSQL error: ${esc(e.message)}</div>` }; }
  const last = [...results].reverse().find((r) => r.fields && r.fields.length);
  if (!last) return { passed: 0, total: 1, failed: ["no result"], html: '<div class="cl-banner warn">Your SQL ran but returned no rows to check. End with a SELECT.</div>' };
  const cols = last.fields.map((f) => f.name);
  const rows = last.rows.map((row) => last.fields.map((f) => row[f.name]));
  const shown = tableHTML({ columns: cols, rows: rows.map((r) => r.map((v) => (v == null ? null : String(v)))) }, 30);
  if (cols[0] === "QUERY PLAN") return { passed: 0, total: 1, failed: ["plan, not result"], html: '<div class="cl-banner warn">That is a plan. Run the query without EXPLAIN to check it.</div>' + shown };
  const how = cols.length === x.expected.columns.length ? compareRows(rows, x.expected.rows) : "";
  if (how === "exact") return { passed: 1, total: 1, html: '<div class="cl-banner good">Matches the expected result.</div>' + shown };
  if (how === "order") return { passed: 0, total: 1, failed: ["row order"], html: '<div class="cl-banner warn">Right rows, wrong order. The problem specifies the ordering.</div>' + shown };
  for (const d of x.diagnostics || []) {
    if (compareRows(rows, d.rows)) return { passed: 0, total: 1, failed: [d.message], diag: d.message, html: `<div class="cl-banner bad">Not yet. ${esc(d.message)}</div>` + shown };
  }
  const note = cols.length !== x.expected.columns.length ? ` It returns ${cols.length} column${cols.length === 1 ? "" : "s"}; the expected result has ${x.expected.columns.length}.` : "";
  return { passed: 0, total: 1, failed: ["does not match"], html: `<div class="cl-banner warn">Does not match the expected result yet.${note}</div>` + shown };
}

let pyWorker = null, pySeq = 0;
async function checkPython(it, tpl, ins, code) {
  const mod = ins.mod, x = ins.inst;
  const needRef = x.tests.some((t) => t.expect == null);
  const ref = needRef ? (await evalData(it.company)).templates[tpl.id].reference_python : "";
  return new Promise((resolve) => {
    if (!pyWorker) pyWorker = new Worker(new URL("py-worker.js", import.meta.url));
    const id = ++pySeq;
    const kill = (html) => { clearTimeout(stop); if (pyWorker) pyWorker.terminate(); pyWorker = null; resolve({ passed: 0, total: x.tests.length, failed: ["stopped"], html }); };
    let stop = setTimeout(() => kill('<div class="cl-banner bad">Python did not finish loading. Check your connection and run again.</div>'), 180000);
    const budget = x.tests.reduce((acc, t) => acc + (t.limit_s || 2) * 1000, 0) + 10000;
    pyWorker.onmessage = (ev) => {
      if (ev.data.id !== id) return;
      if (ev.data.type === "booted") {
        clearTimeout(stop);
        stop = setTimeout(() => kill(`<div class="cl-banner bad">Stopped after ${Math.round(budget / 1000)} s. Your code is looping or far slower than the constraints allow.</div>`), budget);
        return;
      }
      clearTimeout(stop);
      if (!ev.data.ok) { resolve({ passed: 0, total: x.tests.length, failed: ["does not run"], html: `<div class="cl-banner bad">Your code did not run:</div><pre class="detail">${esc(ev.data.error)}</pre>` }); return; }
      const rows = ev.data.results;
      const passed = rows.filter((r) => r.ok).length;
      let h = `<div class="cl-banner ${passed === rows.length ? "good" : "warn"}">${passed} of ${rows.length} tests passed.</div>`;
      for (const r of rows) h += `<div class="row"><span class="${r.ok ? "ok" : "bad"}">${r.ok ? "✓" : "✗"}</span><div>${esc(r.name)} <span class="cl-small cl-muted">(${(r.secs || 0).toFixed(2)} s)</span>${r.ok ? "" : `<div class="detail">got: ${esc(r.got)}${r.want ? "\nexpected: " + esc(r.want) : ""}</div>`}</div></div>`;
      resolve({ passed, total: rows.length, failed: rows.filter((r) => !r.ok).map((r) => r.name), html: h });
    };
    pyWorker.onerror = (e) => kill(`<div class="cl-banner bad">Python could not start: ${esc(e.message || "worker error")}</div>`);
    pyWorker.postMessage({ id, code, ref, entry: mod.entry, prelude: mod.prelude || "", tests: x.tests });
  });
}

