  function loadReported(role) {
    reportedQs().then(function (all) {
      var el = document.getElementById("cp-reported");
      if (!el) return;
      var mine = E.reportedForRole(all, role);
      if (!mine.length) {
        el.innerHTML = '<p class="cp-empty">No publicly reported questions name this role yet. <a href="../reported/">Interview Intelligence</a> adds reports weekly from public sources; nothing is invented to fill the gap. The practice scenarios above are original and labelled as such.</p>';
        return;
      }
      el.innerHTML = '<ul class="cp-reported">' + mine.slice(0, 8).map(function (q) {
        return '<li><a href="../reported/#' + esc(q.id) + '">' + esc(q.title || q.question) + "</a> <span>" + (q.source_count || 0) + " source" + (q.source_count === 1 ? "" : "s") + "</span></li>";
      }).join("") + "</ul>";
    });
  }

  /* ── question work (shared by Practice and Mock) ── */
  function tableHTML(q, revealed) {
    var t = q.table;
    if (!t) return "";
    var cols = t.columns.filter(function (c) { return revealed || !/computed/.test(c[1]); });
    var h = '<div class="cp-table" tabindex="0" role="region" aria-label="Scenario data"><table><thead><tr><th scope="col">Key</th>' +
      cols.map(function (c) { return '<th scope="col">' + esc(c[1]) + "</th>"; }).join("") + "</tr></thead><tbody>";
    t.rows.forEach(function (r) {
      h += '<tr><th scope="row">' + esc(r.key) + "</th>" + cols.map(function (c) {
        var v = r[c[0]];
        if (Array.isArray(v)) v = v.length ? v.join(", ") : "—";
        if (c[0] === "confidence") v = Math.round(v * 100) + "%";
        return "<td>" + esc(v) + "</td>";
      }).join("") + "</tr>";
    });
    h += "</tbody></table></div><p class=\"cp-small\">" + esc(t.unit) + (revealed ? " Computed columns are calculated by the build, not typed." : "") + "</p>";
    if (revealed && t.paths) h += '<p class="cp-small">Critical path(s): ' + esc(t.paths.map(function (p) { return p.join("–"); }).join(", ")) + " · earliest finish week " + t.total + ".</p>";
    return h;
  }

  function promptHTML(q, revealed) {
    return '<p class="cp-kindtag">Original practice scenario — not from any company’s interviews</p>' +
      '<h3 class="cp-qtitle" tabindex="-1">' + esc(q.title) + '</h3><p class="cp-qmeta">' + esc(idx.cat[q.category].title) + " · about " + q.minutes + " min · " +
      q.levels.map(function (l) { return idx.sen[l].label; }).join(", ") + "</p>" +
      (q.premise ? '<p class="cp-premise">' + esc(q.premise) + "</p>" : "") +
      '<blockquote class="cp-prompt">' + esc(q.prompt) + "</blockquote>" + tableHTML(q, revealed);
  }

  function revealHTML(q, saved, dims) {
    var covered = (saved && saved.covered) || [];
    var scores = (saved && saved.scores) || {};
    var h = '<div class="cp-reveal"><h4>Did your answer…</h4><ul class="cp-check">' + q.criteria.map(function (c, i) {
      var id = "cv-" + q.id + "-" + i;
      return '<li><input type="checkbox" id="' + id + '" data-cover="' + i + '"' + (covered.indexOf(i) !== -1 ? " checked" : "") + '><label for="' + id + '">' + esc(c) + "</label></li>";
    }).join("") + "</ul>" +
      '<h4>A structured answer</h4><ol class="cp-outline">' + q.outline.map(function (o) { return "<li>" + esc(o) + "</li>"; }).join("") + "</ol>" +
      '<h4>Reference answer <span class="cp-kind">One strong approach, not the only one</span></h4><div class="cp-ref">' + paras(q.reference) + "</div>" +
      '<h4>Pitfalls</h4><ul>' + q.pitfalls.map(function (o) { return "<li>" + esc(o) + "</li>"; }).join("") + "</ul>" +
      '<h4>Score yourself <span class="cp-kind">Self-assessment · 1 to 4</span></h4><div class="cp-score">';
    dims.forEach(function (d) {
      var dim = idx.dim[d];
      h += '<fieldset><legend>' + esc(dim.name) + '<span class="cp-small"> — ' + esc(dim.listens_for) + "</span></legend>";
      dim.anchors.forEach(function (a, i) {
        var id = "sc-" + q.id + "-" + d + "-" + (i + 1);
        h += '<div class="cp-radio"><input type="radio" name="sc-' + q.id + "-" + d + '" id="' + id + '" value="' + (i + 1) + '" data-dim="' + d + '"' +
          (scores[d] === i + 1 ? " checked" : "") + '><label for="' + id + '"><strong>' + (i + 1) + "</strong> " + esc(a) + "</label></div>";
      });
      h += "</fieldset>";
    });
    return h + "</div></div>";
  }

  function readScores(root) {
    var s = {};
    root.querySelectorAll(".cp-score input:checked").forEach(function (i) { s[i.getAttribute("data-dim")] = Number(i.value); });
    return s;
  }
  function readCovered(root) {
    var c = [];
    root.querySelectorAll("[data-cover]:checked").forEach(function (i) { c.push(Number(i.getAttribute("data-cover"))); });
    return c;
  }

  /* progressive hints / follow-ups: returns html and wires buttons */
  function stepper(kind, items, shownN) {
    var label = kind === "hint" ? "hint" : "follow-up";
    var h = '<div class="cp-step" data-kind="' + kind + '"><ol class="cp-steplist">' + items.slice(0, shownN).map(function (x) {
      return "<li>" + (kind === "follow" ? '<span class="cp-who">Interviewer:</span> ' : "") + esc(x) + "</li>";
    }).join("") + "</ol>";
    if (shownN < items.length) {
      h += '<button type="button" class="cp-btn" data-more="' + kind + '">' + (kind === "hint" ? "Show a hint" : "Ask me a follow-up") +
        " (" + (shownN + 1) + " of " + items.length + ")</button>";
    } else {
      h += '<p class="cp-small">All ' + items.length + " " + label + "s shown.</p>";
    }
    return h + "</div>";
  }

  /* ── 2 · Practice ── */
  function renderPractice(el, role, track, qs) {
    if (view.qid && qs.some(function (q) { return q.id === view.qid; })) return renderPracticeQuestion(el, role, track, qs);
    var level = P.level || role.level;
    var cats = track.categories;
    var rows = qs.filter(function (q) {
      return (!view.cat || q.category === view.cat) && (!view.levelOnly || q.levels.indexOf(level) !== -1);
    });
    var h = '<h2 class="cp-h2">Practice questions</h2><p class="cp-small">Answer in writing or out loud, then compare with the criteria and a reference answer. Your notes stay in this browser.</p>' +
      '<div class="cp-filters"><label for="cp-cat">Category</label><select id="cp-cat"><option value="">All categories</option>' +
      cats.map(function (c) { return '<option value="' + c + '"' + (view.cat === c ? " selected" : "") + ">" + esc(idx.cat[c].title) + "</option>"; }).join("") +
      '</select><span class="cp-opt"><input type="checkbox" id="cp-lvl"' + (view.levelOnly ? " checked" : "") + '><label for="cp-lvl">Only questions written for ' +
      esc(idx.sen[level].label) + "</label></span></div>";
    if (!rows.length) {
      h += '<p class="cp-empty">No questions in this category are written for ' + esc(idx.sen[level].label) + ' level. <button type="button" class="cp-link" id="cp-lvl-off">Show all levels</button></p>';
    } else {
      h += '<ul class="cp-qlist">' + rows.map(function (q) {
        var done = store.practice[q.id];
        return '<li><button type="button" class="cp-qrow" data-q="' + q.id + '"><span class="t">' + esc(q.title) + '</span><span class="m">' +
          esc(idx.cat[q.category].title) + " · " + q.minutes + " min" + (done ? ' · <span class="cp-done">practised ' + fmtDate(done.at) + "</span>" : "") +
          "</span></button></li>";
      }).join("") + "</ul>";
    }
    el.innerHTML = h;
    el.querySelector("#cp-cat").addEventListener("change", function (e) { view.cat = e.target.value; renderPractice(el, role, track, qs); el.querySelector("#cp-cat").focus(); });
    el.querySelector("#cp-lvl").addEventListener("change", function (e) { view.levelOnly = e.target.checked; renderPractice(el, role, track, qs); el.querySelector("#cp-lvl").focus(); });
    var off = el.querySelector("#cp-lvl-off");
    if (off) off.addEventListener("click", function () { view.levelOnly = false; renderPractice(el, role, track, qs); });
    el.querySelectorAll("[data-q]").forEach(function (b) {
      b.addEventListener("click", function () { view.qid = b.getAttribute("data-q"); renderPractice(el, role, track, qs); });
    });
  }

  function renderPracticeQuestion(el, role, track, qs) {
    var q = qs.filter(function (x) { return x.id === view.qid; })[0];
    var st = view.timers[q.id] || (view.timers[q.id] = { hints: 0, follows: 0, revealed: false, running: false, elapsed: 0, last: 0 });
    var saved = store.practice[q.id];
    var h = '<button type="button" class="cp-back" id="cp-back">← All practice questions</button>' + promptHTML(q, st.revealed) +
      '<div class="cp-timer"><span role="timer" aria-label="Elapsed time" id="cp-pt">' + fmtClock(st.elapsed) + "</span> <span class=\"cp-small\">of about " + q.minutes + ' min</span> ' +
      '<button type="button" class="cp-btn" id="cp-pt-go">' + (st.running ? "Pause" : st.elapsed ? "Resume timer" : "Start timer (optional)") + "</button></div>" +
      '<label class="cp-alabel" for="cp-ans">Your answer <span class="cp-small">(saved in this browser only)</span></label>' +
      '<textarea id="cp-ans" rows="10" spellcheck="true">' + esc(store.answers[q.id] || "") + "</textarea>" +
      '<div class="cp-two"><div><h4>Hints</h4>' + stepper("hint", q.hints, st.hints) + "</div><div><h4>Follow-ups</h4>" + stepper("follow", q.followups, st.follows) + "</div></div>";
    if (!st.revealed) {
      h += '<button type="button" class="cp-btn is-primary" id="cp-reveal">Reveal criteria and reference answer</button>';
    } else {
      h += revealHTML(q, saved, q.dimensions) + '<button type="button" class="cp-btn is-primary" id="cp-save">Save my self-assessment</button> <span class="cp-small" id="cp-saved">' +
        (saved ? "Last saved " + fmtDate(saved.at) : "") + "</span>";
    }
    el.innerHTML = h;
    el.querySelector("#cp-back").addEventListener("click", function () { view.qid = null; stopTick(); renderPractice(el, role, track, qs); });
    el.querySelector("#cp-ans").addEventListener("input", function (e) { store.answers[q.id] = e.target.value; save(); });
    el.querySelectorAll("[data-more]").forEach(function (b) {
      b.addEventListener("click", function () {
        if (b.getAttribute("data-more") === "hint") st.hints++; else st.follows++;
        rerender(b.getAttribute("data-more"));
      });
    });
    function rerender(focusKind) {
      renderPracticeQuestion(el, role, track, qs);
      var list = el.querySelector('.cp-step[data-kind="' + focusKind + '"] .cp-steplist li:last-child');
      if (list) { list.tabIndex = -1; list.focus(); }
    }
    el.querySelector("#cp-pt-go").addEventListener("click", function () {
      st.running = !st.running;
      st.last = Date.now();
      el.querySelector("#cp-pt-go").textContent = st.running ? "Pause" : "Resume timer";
      if (st.running) startTick(function () {
        var now = Date.now();
        st.elapsed += (now - st.last) / 1000;
        st.last = now;
        var t = document.getElementById("cp-pt");
        if (t) t.textContent = fmtClock(st.elapsed);
      }); else stopTick();
    });
    if (st.running) { st.last = Date.now(); startTick(function () { var now = Date.now(); st.elapsed += (now - st.last) / 1000; st.last = now; var t = document.getElementById("cp-pt"); if (t) t.textContent = fmtClock(st.elapsed); }); }
    var rv = el.querySelector("#cp-reveal");
    if (rv) rv.addEventListener("click", function () {
      st.revealed = true;
      renderPracticeQuestion(el, role, track, qs);
      var h4 = el.querySelector(".cp-reveal h4");
      if (h4) { h4.tabIndex = -1; h4.focus(); }
    });
    var sv = el.querySelector("#cp-save");
    if (sv) sv.addEventListener("click", function () {
      store.practice[q.id] = { at: Date.now(), scores: readScores(el), covered: readCovered(el), role: role.id };
      save(true);
      el.querySelector("#cp-saved").textContent = "Saved.";
      announce("Self-assessment saved.");
    });
    var title = el.querySelector(".cp-qtitle");
    if (title && document.activeElement === el) title.focus();
  }

  function startTick(fn) { stopTick(); tick = setInterval(fn, 1000); }
  function stopTick() { if (tick) clearInterval(tick); tick = null; }

  /* ── 3 · Mock interview ── */
  function renderMock(el, role, track, qs) {
    var cur = store.current;
    if (cur && cur.role !== role.id) {
      el.innerHTML = '<p class="cp-note">You have an unfinished mock interview for ' + esc(idx.role[cur.role] ? idx.role[cur.role].title : cur.role) +
        '. <a href="' + esc(href({ role: cur.role, level: cur.level, company: cur.company }, "mock")) + '">Continue it</a> or <button type="button" class="cp-link" id="cp-drop">discard it</button> to start one for this role.</p>';
      el.querySelector("#cp-drop").addEventListener("click", function () { store.current = null; save(true); renderMock(el, role, track, qs); });
      return;
    }
    if (!cur) return mockIntro(el, role, track, qs);
    mockRound(el, role, track, qs);
  }

  function mockIntro(el, role, track, qs) {
    var level = P.level || role.level;
    var plan = track.rounds;
    el.innerHTML = '<h2 class="cp-h2">A five-round mock interview</h2><p class="cp-lead">Five rounds as a ' + esc(track.title) +
      " loop commonly runs them. Each round is timed; hints are there if you want them and are recorded; the interviewer’s follow-ups arrive one at a time. At the end of each round you score yourself against the rubric.</p>" +
      '<ol class="cp-rounds">' + plan.map(function (r) {
        return "<li><strong>" + esc(r.title) + '</strong> <span class="cp-small">' + r.minutes + " min</span><br><span class=\"cp-small\">" + esc(r.focus) + "</span></li>";
      }).join("") + "</ol>" +
      '<p class="cp-small">Level: ' + esc(idx.sen[level].label) + (P.company ? " · Company context: " + esc(P.company) + " (questions are original practice, not the company’s)" : "") +
      ". Real loops vary between organisations, levels and teams; this is a practice structure, and the result is your own self-assessment, not a prediction of any hiring outcome.</p>" +
      '<button type="button" class="cp-btn is-primary" id="cp-start">Start the mock interview</button>';
    el.querySelector("#cp-start").addEventListener("click", function () {
      var seed = Math.floor(Math.random() * 1e9);
      var p = E.roundPlan(track, qs, level, seed);
      store.current = {
        id: "m" + Date.now().toString(36), role: role.id, track: track.id, level: level, company: P.company || "",
        job: P.job || "", seed: seed, started: Date.now(), i: 0,
        rounds: p.map(function (r) { return { n: r.n, title: r.title, minutes: r.minutes, qid: r.qid, elapsed: 0, hints: 0, follows: 0, answer: "", ended: false, scores: {}, covered: [] }; })
      };
      save(true);
      mockRound(el, role, track, qs, true);
    });
  }

  function mockRound(el, role, track, qs, focus) {
    var cur = store.current;
    var r = cur.rounds[cur.i];
    var byId = {};
    qs.forEach(function (q) { byId[q.id] = q; });
    var q = byId[r.qid];
    if (!q) { store.current = null; save(true); return mockIntro(el, role, track, qs); }
    var remaining = r.minutes * 60 - r.elapsed;
    var h = '<div class="cp-mockbar"><span class="cp-progress">Round ' + r.n + " of 5 · " + esc(r.title) + "</span>" +
      '<span class="cp-clock' + (remaining < 0 ? " is-over" : "") + '"><span role="timer" aria-label="Time remaining in this round" id="cp-mt">' + fmtClock(remaining) +
      '</span> <span class="cp-small">' + (remaining < 0 ? "over time" : "left") + "</span></span>" +
      (r.ended ? "" : '<button type="button" class="cp-btn" id="cp-mpause">' + (view.mockRunning ? "Pause" : "Start clock") + "</button>") + "</div>" +
      promptHTML(q, r.ended);
    if (!r.ended) {
      if (!r.answer && r.elapsed < 60) h += '<button type="button" class="cp-link" id="cp-swap">Give me a different question for this round</button>';
      h += '<label class="cp-alabel" for="cp-mans">Your answer</label><textarea id="cp-mans" rows="11">' + esc(r.answer) + "</textarea>" +
        '<div class="cp-two"><div><h4>Hints <span class="cp-small">(optional; recorded)</span></h4>' + stepper("hint", q.hints, r.hints) + "</div>" +
        "<div><h4>Interviewer follow-ups</h4>" + stepper("follow", q.followups, r.follows) + "</div></div>" +
        '<button type="button" class="cp-btn is-primary" id="cp-end">Finish this round</button> <button type="button" class="cp-link" id="cp-quit">Abandon the mock</button>';
    } else {
      h += '<details class="cp-youranswer"><summary>Your answer</summary><div>' + paras(r.answer || "(no written answer)") + "</div></details>" +
        '<div class="cp-two"><div><h4>Hints used</h4><p>' + r.hints + " of " + q.hints.length + "</p></div><div><h4>Follow-ups</h4>" + stepper("follow", q.followups, q.followups.length) + "</div></div>" +
        revealHTML(q, r, q.dimensions) +
        '<button type="button" class="cp-btn is-primary" id="cp-next">' + (cur.i < 4 ? "Save and go to round " + (r.n + 1) : "Save and see my results") + "</button>";
    }
    el.innerHTML = h;
    if (focus) { var t = el.querySelector(".cp-progress"); t.tabIndex = -1; t.focus(); }

    var clockTick = function () {
      var now = Date.now();
      r.elapsed += (now - view.mockLast) / 1000;
      view.mockLast = now;
      var left = r.minutes * 60 - r.elapsed;
      var tEl = document.getElementById("cp-mt");
      if (tEl) tEl.textContent = fmtClock(left);
      if (Math.floor(left) === 300) announce("Five minutes left in this round.");
      if (Math.floor(left) === 0) announce("Time is up for this round. Finish when you are ready.");
      if (left < 0 && tEl) tEl.parentNode.classList.add("is-over");
      save();
    };
    if (!r.ended && view.mockRunning) { view.mockLast = Date.now(); startTick(clockTick); }
    var pause = el.querySelector("#cp-mpause");
    if (pause) pause.addEventListener("click", function () {
      view.mockRunning = !view.mockRunning;
      pause.textContent = view.mockRunning ? "Pause" : "Resume clock";
      if (view.mockRunning) { view.mockLast = Date.now(); startTick(clockTick); } else { stopTick(); save(true); }
    });
    var swap = el.querySelector("#cp-swap");
    if (swap) swap.addEventListener("click", function () {
      var plan = cur.rounds.map(function (x) { return { qid: x.qid }; });
      r.qid = E.swapQuestion(track, plan, cur.i, qs, cur.level, Date.now() & 0xffff);
      save(true);
      mockRound(el, role, track, qs);
      announce("New question for this round.");
    });
    var ans = el.querySelector("#cp-mans");
    if (ans) ans.addEventListener("input", function () {
      r.answer = ans.value;
      if (!view.mockRunning) { view.mockRunning = true; view.mockLast = Date.now(); startTick(clockTick); if (pause) pause.textContent = "Pause"; }
      save();
    });
    el.querySelectorAll("[data-more]").forEach(function (b) {
      b.addEventListener("click", function () {
        if (b.getAttribute("data-more") === "hint") r.hints++; else r.follows++;
        save(true);
        var kind = b.getAttribute("data-more");
        stopTick();
        mockRound(el, role, track, qs);
        var li = el.querySelector('.cp-step[data-kind="' + kind + '"] .cp-steplist li:last-child');
        if (li) { li.tabIndex = -1; li.focus(); }
      });
    });
    var end = el.querySelector("#cp-end");
    if (end) end.addEventListener("click", function () {
      stopTick();
      view.mockRunning = false;
      r.ended = true;
      save(true);
      mockRound(el, role, track, qs);
      var h4 = el.querySelector(".cp-reveal h4");
      if (h4) { h4.tabIndex = -1; h4.focus(); }
    });
    var quit = el.querySelector("#cp-quit");
    if (quit) quit.addEventListener("click", function () {
      if (!confirm("Abandon this mock interview? Your answers for it will be discarded.")) return;
      stopTick();
      view.mockRunning = false;
      store.current = null;
      save(true);
      mockIntro(el, role, track, qs);
    });
    var next = el.querySelector("#cp-next");
    if (next) next.addEventListener("click", function () {
      r.scores = readScores(el);
      r.covered = readCovered(el);
      if (cur.i < 4) {
        cur.i++;
        save(true);
        mockRound(el, role, track, qs, true);
        return;
      }
      var done = {
        id: cur.id, role: cur.role, track: cur.track, level: cur.level, company: cur.company, job: cur.job,
        started: cur.started, finished: Date.now(),
        rounds: cur.rounds.map(function (x) {
          return { n: x.n, title: x.title, qid: x.qid, seconds: Math.round(x.elapsed), minutes: x.minutes, hints: x.hints, follows: x.follows, scores: x.scores, covered: x.covered };
        })
      };
      cur.rounds.forEach(function (x) { if (x.answer) store.answers[x.qid] = x.answer; });
      store.attempts.push(done);
      store.attempts = store.attempts.slice(-50);
      store.current = null;
      save(true);
      announce("Mock interview complete. Showing your results.");
      selectTab("results", true);
    });
  }

  /* ── 4 · Results ── */
  function renderResults(el, role, track, qs) {
    var mine = store.attempts.filter(function (a) { return a.role === role.id; }).slice().reverse();
    var byId = {};
    qs.forEach(function (q) { byId[q.id] = q; });
    if (!mine.length) {
      el.innerHTML = '<h2 class="cp-h2">Results</h2><p class="cp-empty">No completed mock interview for this role yet. Results appear here after all five rounds.</p>' +
        '<button type="button" class="cp-btn is-primary" id="cp-gomock">Go to the mock interview</button>';
      el.querySelector("#cp-gomock").addEventListener("click", function () { selectTab("mock", true); });
      return;
    }
    var a = mine[0];
    var avgs = E.dimAverages(a), ov = E.overall(a);
    var weak = E.weakest(avgs, 2, track.rubric_all);
    var rec = E.recommend(qs, weak, store.practice, 4);
    var h = '<h2 class="cp-h2">Your latest mock — ' + esc(fmtDate(a.finished)) + "</h2>" +
      '<p class="cp-disclaim">This is your own self-assessment against the rubric. It is practice feedback, not a prediction of any hiring outcome.</p>' +
      '<p class="cp-big">' + (ov == null ? "Not scored" : ov.toFixed(1) + ' <span>/ 4 average across the dimensions you scored</span>') + "</p>" +
      '<div class="cp-table" tabindex="0" role="region" aria-label="Rounds"><table><thead><tr><th scope="col">Round</th><th scope="col">Question</th><th scope="col">Time</th><th scope="col">Hints</th><th scope="col">Follow-ups</th><th scope="col">Your average</th></tr></thead><tbody>' +
      a.rounds.map(function (r) {
        var ra = E.roundAverage(r);
        return '<tr><th scope="row">' + r.n + " · " + esc(r.title) + "</th><td>" + esc(byId[r.qid] ? byId[r.qid].title : r.qid) + "</td><td>" +
          fmtClock(r.seconds) + " of " + r.minutes + ":00</td><td>" + r.hints + "</td><td>" + r.follows + "</td><td>" + (ra == null ? "—" : ra.toFixed(1)) + "</td></tr>";
      }).join("") + "</tbody></table></div>";
    var dims = Object.keys(avgs).sort(function (x, y) { return avgs[x] - avgs[y]; });
    if (dims.length) {
      h += '<h3 class="cp-h3">By dimension</h3><ul class="cp-bars">' + dims.map(function (d) {
        var v = avgs[d];
        return '<li><span class="l">' + esc(idx.dim[d].name) + '</span><span class="bar" aria-hidden="true"><span style="width:' + (v / 4 * 100) + '%"></span></span><span class="v">' +
          v.toFixed(1) + " · " + esc(D.rubric.scale[Math.max(0, Math.round(v) - 1)].label) + "</span></li>";
      }).join("") + "</ul>";
    }
    if (weak.length) {
      h += '<h3 class="cp-h3">Focus next</h3><p>Your lowest self-scores: ' + weak.map(function (d) { return "<strong>" + esc(idx.dim[d].name) + "</strong>"; }).join(" and ") +
        ". These questions exercise them:</p><ul class=\"cp-elsewhere\">" + rec.map(function (id) {
          return '<li><button type="button" class="cp-link" data-practise="' + id + '">' + esc(byId[id].title) + "</button> <span class=\"cp-small\">" + esc(idx.cat[byId[id].category].title) + "</span></li>";
        }).join("") + "</ul>";
    } else if (dims.length) {
      h += '<p class="cp-note">You scored yourself 3 or higher everywhere. Try the loop at the next seniority level, or ask a colleague to score you against the same anchors.</p>';
    }
    if (mine.length > 1) {
      h += '<h3 class="cp-h3">Earlier mocks for this role</h3><ul class="cp-hist">' + mine.slice(1, 10).map(function (x) {
        var o = E.overall(x);
        return "<li>" + esc(fmtDate(x.finished)) + " · " + esc(idx.sen[x.level] ? idx.sen[x.level].label : x.level) + (x.company ? " · " + esc(x.company) : "") +
          " · " + (o == null ? "not scored" : o.toFixed(1) + " / 4") + "</li>";
      }).join("") + "</ul>";
    }
    h += '<p class="cp-small">Stored only in this browser. <button type="button" class="cp-link" id="cp-wipe">Delete all my Career Prep data</button></p>';
    el.innerHTML = h;
    el.querySelectorAll("[data-practise]").forEach(function (b) {
      b.addEventListener("click", function () { view.qid = b.getAttribute("data-practise"); selectTab("practice", true); });
    });
    el.querySelector("#cp-wipe").addEventListener("click", function () {
      if (!confirm("Delete every Career Prep answer, self-assessment and mock result stored in this browser?")) return;
      store = { v: 1, answers: {}, practice: {}, attempts: [], current: null };
      try { localStorage.removeItem(KEY); } catch (e) { /* nothing to remove */ }
      renderResults(el, role, track, qs);
      announce("Career Prep data deleted.");
    });
  }

