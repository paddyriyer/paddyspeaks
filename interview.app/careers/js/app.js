  /* ── helpers ── */
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function paras(text) {
    return String(text || "").split(/\n\n+/).map(function (p) { return "<p>" + esc(p) + "</p>"; }).join("");
  }
  function announce(msg) { announcer.textContent = ""; setTimeout(function () { announcer.textContent = msg; }, 30); }
  function getJSON(u) {
    return fetch(u, { cache: "no-cache" }).then(function (r) {
      if (!r.ok) throw new Error("HTTP " + r.status);
      return r.json();
    });
  }
  function fmtClock(sec) {
    var s = Math.abs(Math.round(sec)), m = Math.floor(s / 60);
    return (sec < 0 ? "+" : "") + m + ":" + String(s % 60).padStart(2, "0");
  }
  function fmtDate(ts) {
    var d = new Date(ts);
    return isNaN(d) ? "" : d.toLocaleDateString(undefined, { day: "numeric", month: "short", year: "numeric" });
  }

  /* ── storage (never throws; the page works without it) ── */
  function load() {
    try {
      var s = JSON.parse(localStorage.getItem(KEY) || "null");
      if (s && s.v === 1) return s;
    } catch (e) { /* private mode or corrupt: start fresh */ }
    return { v: 1, answers: {}, practice: {}, attempts: [], current: null };
  }
  var store = load();
  var saveTimer = null;
  function save(now) {
    clearTimeout(saveTimer);
    var write = function () {
      try {
        localStorage.setItem(KEY, JSON.stringify(store));
        var days = JSON.parse(localStorage.getItem("ps-activity-days") || "[]");
        var d = new Date(), k = d.getFullYear() + "-" + String(d.getMonth() + 1).padStart(2, "0") + "-" + String(d.getDate()).padStart(2, "0");
        if (days.indexOf(k) === -1) { days.push(k); localStorage.setItem("ps-activity-days", JSON.stringify(days)); }
      } catch (e) { /* storage unavailable */ }
    };
    if (now) write(); else saveTimer = setTimeout(write, 400);
  }

  /* ── routing ── */
  function readParams() {
    var p = new URLSearchParams(location.search);
    P = {
      role: p.get("role") || "", family: p.get("family") || "", company: (p.get("company") || "").slice(0, 80),
      level: p.get("level") || "", job: p.get("job") || "", start: p.get("start") || "", q: p.get("q") || ""
    };
    if (P.role && !idx.role[P.role]) P.role = "";
    if (P.level && !idx.sen[P.level]) P.level = "";
    if (P.family && !idx.fam[P.family]) P.family = "";
    var h = location.hash.replace("#", "");
    var tab = TABS.some(function (t) { return t[0] === h; }) ? h : (TABS.some(function (t) { return t[0] === P.start; }) ? P.start : "topics");
    view.tab = tab;
  }
  function href(params, hash) {
    var p = new URLSearchParams();
    ["role", "level", "company", "job", "family"].forEach(function (k) { if (params[k]) p.set(k, params[k]); });
    var s = p.toString();
    return location.pathname + (s ? "?" + s : "") + (hash ? "#" + hash : "");
  }
  function go(params, hash, replace) {
    history[replace ? "replaceState" : "pushState"](null, "", href(params, hash));
    readParams();
    render();
  }
  window.addEventListener("popstate", function () { readParams(); render(); });

  /* ── data ── */
  function questions(trackId) {
    if (qcache[trackId]) return Promise.resolve(qcache[trackId]);
    return getJSON("data/tracks/" + trackId + ".json").then(function (d) {
      qcache[trackId] = d.questions;
      return d.questions;
    });
  }
  function board() {
    if (jobsBoard) return Promise.resolve(jobsBoard);
    return getJSON("../jobs/data/jobs.json").then(function (d) { jobsBoard = d; return d; });
  }
  function reportedQs() {
    if (reported) return Promise.resolve(reported);
    return getJSON("../reported/data/questions.json").then(function (d) {
      reported = d.questions || [];
      return reported;
    }).catch(function () { reported = []; return reported; });
  }

