  function wireRoleHead(role) {
    app.querySelector("#cp-level").addEventListener("change", function (e) {
      go({ role: role.id, level: e.target.value, company: P.company, job: P.job }, view.tab, true);
    });
  }

  function panel(id) { return document.getElementById("panel-" + id); }

  function wireTabs() {
    var list = app.querySelector(".cp-tabs");
    list.addEventListener("click", function (e) {
      var b = e.target.closest('[role="tab"]');
      if (b) selectTab(b.id.replace("tab-", ""), true);
    });
    list.addEventListener("keydown", function (e) {
      var tabs = Array.prototype.slice.call(list.querySelectorAll('[role="tab"]'));
      var i = tabs.indexOf(document.activeElement);
      if (i === -1) return;
      var j = e.key === "ArrowRight" ? (i + 1) % tabs.length : e.key === "ArrowLeft" ? (i - 1 + tabs.length) % tabs.length
        : e.key === "Home" ? 0 : e.key === "End" ? tabs.length - 1 : -1;
      if (j === -1) return;
      e.preventDefault();
      tabs[j].focus();
      selectTab(tabs[j].id.replace("tab-", ""), false);
    });
  }

  function selectTab(id, focusPanel) {
    view.tab = id;
    if (id !== "practice") view.qid = view.qid; // keep the open practice question
    history.replaceState(null, "", href({ role: P.role, level: P.level, company: P.company, job: P.job }, id));
    app.querySelectorAll('[role="tab"]').forEach(function (b) {
      var on = b.id === "tab-" + id;
      b.setAttribute("aria-selected", on);
      b.tabIndex = on ? 0 : -1;
    });
    app.querySelectorAll('[role="tabpanel"]').forEach(function (p) { p.hidden = p.id !== "panel-" + id; });
    var role = idx.role[P.role], track = idx.track[role.track];
    questions(track.id).then(function (qs) {
      renderPanel(id, role, track, qs);
      if (focusPanel) panel(id).focus();
    });
  }

  function renderPanel(id, role, track, qs) {
    stopTick();
    var el = panel(id);
    if (!el) return;
    if (id === "topics") el.innerHTML = topicsHTML(role, track, qs);
    if (id === "practice") renderPractice(el, role, track, qs);
    if (id === "mock") renderMock(el, role, track, qs);
    if (id === "results") renderResults(el, role, track, qs);
    if (id === "apply") renderApply(el, role);
    if (id === "topics") {
      el.querySelectorAll("[data-practise]").forEach(function (b) {
        b.addEventListener("click", function () { view.qid = b.getAttribute("data-practise"); selectTab("practice", true); });
      });
      loadReported(role);
    }
  }

