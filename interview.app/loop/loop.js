      if (!answered(mode, q.id)) why.push("no answer");
      if (c && c.passed < c.total) why.push("checks " + c.passed + "/" + c.total);
      const s = scoreOf(q); if (!Number.isNaN(s) && s < 2.5) why.push("self-score " + fmt(s));
