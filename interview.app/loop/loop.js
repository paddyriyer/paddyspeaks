/* ============================================================
   The Five-Round Loop — Interview Studio
   Practice · Mock interview · Assessment over one question bank.

   Data (GENERATED by interview/loop/build.py — never edit by hand):
     data/questions.json   candidate-facing; loaded at start
     data/solutions.json   evaluator notes; fetched only when a solution is
                           revealed (Practice) or after a mock or assessment ends
   Checks run in the browser: Python in a Web Worker (py-worker.js, Pyodide),
   SQL in PGlite (in-browser PostgreSQL). Scores are the candidate's own,
   against the reference notes; nothing here pretends to grade free text.
   ============================================================ */

