  const el = $("#report");
  if (!el) return;
  const b = bucket(mode);
  const qs = b.qids.map((id) => Q[id]);
  const scoreOf = (q) => avg(q.competencies.map((c) => (b.scores[q.id] || {})[c]));
  const scored = qs.filter((q) => !Number.isNaN(scoreOf(q)));
  if (!scored.length) { el.innerHTML = '<div class="lp-report"><h2>Report</h2><p class="lp-muted">Score at least one question to see your report.</p></div>'; return; }

