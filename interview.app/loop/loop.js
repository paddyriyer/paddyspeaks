function fmtClock(ms) {
  const neg = ms < 0; ms = Math.abs(ms);
  const s = Math.floor(ms / 1000), h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = s % 60;
  const t = (h ? h + ":" + String(m).padStart(2, "0") : m) + ":" + String(sec).padStart(2, "0");
  return (neg ? "−" : "") + t;
}
function listItems(html) {
  // The <li> items of a rendered section, as HTML strings (for one-at-a-time reveals).
  const doc = new DOMParser().parseFromString("<div>" + (html || "") + "</div>", "text/html");
  const ol = doc.querySelector("ol");
  if (!ol) return [];
  return Array.from(ol.children).filter((li) => li.tagName === "LI").map((li) => li.innerHTML);
}
function plain(html) {
  const d = new DOMParser().parseFromString("<div>" + (html || "") + "</div>", "text/html");
  d.querySelectorAll("li").forEach((li) => li.prepend("- "));
  d.querySelectorAll("p,li,pre,tr,h3,h4").forEach((el) => el.append("\n"));
  d.querySelectorAll("td,th").forEach((el) => el.append(" | "));
  return d.body.textContent.replace(/\n{3,}/g, "\n\n").trim();
}
