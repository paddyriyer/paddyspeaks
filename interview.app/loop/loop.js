function reviewStatus(mode, id) {
  const sc = bucket(mode).scores[id] || {};
  const q = Q[id];
  const n = q.competencies.filter((c) => sc[c] != null).length;
  if (!answered(mode, id)) return "— no answer" + (n ? " · scored" : "");
  return n === q.competencies.length ? "— scored " + avg(q.competencies.map((c) => sc[c])).toFixed(1) + " / 4" : n ? "— partly scored" : "— not scored yet";
}
const avg = (xs) => { const v = xs.filter((x) => x != null); return v.length ? v.reduce((a, x) => a + x, 0) / v.length : NaN; };
const fmt = (x) => (Number.isNaN(x) ? "—" : x.toFixed(1));

