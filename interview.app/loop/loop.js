/* ------------------------------------------------------------ storage */

function fresh() {
  return {
    v: 1,
    mode: "practice",
    current: "R1-01",
    settings: { rounds: [1, 2, 3, 4, 5], levels: LEVELS.slice(), pace: 1 },
    practice: { answers: {}, checks: {}, scores: {}, ai: {}, revealed: {} },
    mock: null,
    assess: null,
  };
}
function load() {
  try {
    const s = JSON.parse(localStorage.getItem(STORE_KEY));
    if (s && s.v === 1) return Object.assign(fresh(), s);
  } catch (_e) { /* private mode or bad JSON: start fresh */ }
  return fresh();
}
let saveTimer = null;
function save(now) {
  const write = () => { try { localStorage.setItem(STORE_KEY, JSON.stringify(state)); } catch (_e) { /* storage full or blocked */ } };
  clearTimeout(saveTimer);
  if (now) write(); else saveTimer = setTimeout(write, 300);
}

