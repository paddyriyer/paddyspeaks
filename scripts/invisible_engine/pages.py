def available() -> dict[int, object]:
    out = {}
    for n, _, _ in PLAN:
        if (CONTENT / f'm{n:02d}.py').exists():
            out[n] = importlib.import_module(f'content.m{n:02d}')
    return out


def mods(avail) -> list[tuple]:
    return [(n, t, f'm{n:02d}.html' if n in avail else None, ph) for n, t, ph in PLAN]


def svg_desc(n: int) -> str:
    t = (ROOT / 'scenes' / f's{n:02d}.svg').read_text(encoding='utf-8')
    m = re.search(r'<desc>(.*?)</desc>', t, re.S)
    return html.unescape(m.group(1)) if m else ''


