def module_page(mod, avail):
    M = mod.M
    inserts = getattr(mod, 'INSERTS', {})
    page = M['file']
    body = head(f"Module {M['num']}: {M['title']}", M['dek'], page, avail)
    body += f'''<main id="main">
<div class="ie-head">
  <p class="ie-kicker">{M['kicker']}</p>
  <h1>{M['title']}</h1>
  <p class="dek">{M['dek']}</p>
  <div class="ie-meta"><span>Scenes {M['scenes'][0]['id']:02d}–{M['scenes'][-1]['id']:02d}</span><span>Prerequisites: {M['prereq']}</span></div>
</div>
{LEVELBAR}
<div class="ie-wrap">
{LEGEND}
{getattr(mod, 'BEFORE', '')}
'''
    for sc in M['scenes']:
        body += scene_html(sc)
        body += inserts.get(sc['id'], '')
    body += getattr(mod, 'AFTER', '')
    n = M['num']
    earlier = [k for k in avail if k < n]  # the nearest module that exists, never a missing page
    prev_l = f'<a href="/invisible-engine/m{max(earlier):02d}.html">← Module {max(earlier)}</a>' if earlier else '<a href="/invisible-engine/">← Lesson home</a>'
    nxt = [m for m in PLAN if m[0] == n + 1]
    if not nxt:
        next_l = '<a href="/invisible-engine/">Lesson home →</a>'
    elif n + 1 in avail:
        next_l = f'<a href="/invisible-engine/m{n + 1:02d}.html">Module {n + 1}: {nxt[0][1]} →</a>'
    else:
        next_l = f'<span>Next: Module {n + 1}, {nxt[0][1]} — coming in phase {nxt[0][2]}</span>'
    body += f'<nav class="pager" aria-label="Modules">{prev_l}{next_l}</nav>\n</div>\n</main>\n'
    body += tail(page, getattr(mod, 'SCRIPTS', ()))
    return body


