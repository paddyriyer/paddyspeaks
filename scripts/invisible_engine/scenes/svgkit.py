"""Shared SVG scene helpers for The Invisible Engine.

The scene modules (module01.py, …) are the SOURCE of every diagram. The .svg
files in invisible-engine/scenes/ are GENERATED by scripts/invisible_engine/build.py
(CI runs it with --check); the PNGs by render.mjs. Never hand-edit a generated SVG.
"""
from xml.sax.saxutils import escape as esc

COL = {
    'energy': '#c2410c', 'signal': '#1d4ed8', 'plain': '#15803d', 'crypto': '#7e22ce',
    'admin': '#4b5563', 'hazard': '#b91c1c', 'ink': '#14213d', 'muted': '#4b5563',
}
LEGEND = {
    'energy': 'Energy / power', 'signal': 'Radio signal or wave', 'plain': 'Plaintext / local information',
    'crypto': 'Encrypted / cryptographic', 'admin': 'Registration / authorisation (not data)',
    'hazard': 'Attacker zone / hazard', 'bound': 'Trust or hardware boundary',
}

STYLE = """
    .bg{fill:#ffffff}
    text{font-family:Inter,'Helvetica Neue',Arial,sans-serif;fill:#1f2937}
    .k{font-family:'JetBrains Mono',Menlo,Consolas,monospace;font-size:17px;letter-spacing:2px;fill:#1d4ed8}
    .h{font-size:34px;font-weight:700;fill:#14213d}
    .t{font-size:21px}
    .tb{font-size:21px;font-weight:700;fill:#14213d}
    .s{font-size:17px;fill:#4b5563}
    .sb{font-size:17px;font-weight:700;fill:#14213d}
    .m{font-family:'JetBrains Mono',Menlo,Consolas,monospace;font-size:16px;fill:#14213d}
    .note{font-size:16px;font-style:italic;fill:#4b5563}
    .box{fill:#f8fafc;stroke:#64748b;stroke-width:2}
    .boxw{fill:#ffffff;stroke:#64748b;stroke-width:2}
    .bound{fill:none;stroke:#14213d;stroke-width:5}
    .hz{fill:#fef2f2;stroke:#b91c1c;stroke-width:3;stroke-dasharray:12 8}
    .lab{fill:#ffffff;stroke:#cbd5e1;stroke-width:1}
    .wire{fill:none;stroke:#334155;stroke-width:3}
    .coil{fill:none;stroke:#b45309;stroke-width:4}
    .field{fill:none;stroke:#1d4ed8;stroke-width:2;stroke-dasharray:6 6;opacity:.75}
    .a-energy{stroke:#c2410c;stroke-width:5;fill:none}
    .a-signal{stroke:#1d4ed8;stroke-width:5;fill:none}
    .a-plain{stroke:#15803d;stroke-width:5;fill:none}
    .a-crypto{stroke:#7e22ce;stroke-width:5;fill:none}
    .a-admin{stroke:#4b5563;stroke-width:4;fill:none;stroke-dasharray:12 9}
    .c-energy{fill:#c2410c}.c-signal{fill:#1d4ed8}.c-plain{fill:#15803d}.c-crypto{fill:#7e22ce}.c-admin{fill:#4b5563}.c-hazard{fill:#b91c1c}
"""


class Scene:
    def __init__(self, num, title, desc, kicker=None, sub=None):
        self.num, self.title, self.desc, self.sub = num, title, desc, sub
        self.kicker = kicker or f'SCENE {num:02d}'
        self.parts = []          # (frame, svg)
        self.used = set()
        self.frame = 0

    def f(self, n):
        self.frame = n
        return self

    def add(self, s):
        self.parts.append((self.frame, s))

    # primitives -------------------------------------------------------
    def text(self, x, y, s, cls='t', anchor='start', **kw):
        extra = ''.join(f' {k.replace("_", "-")}="{v}"' for k, v in kw.items())
        lines = s.split('\n')
        if len(lines) == 1:
            self.add(f'<text x="{x}" y="{y}" class="{cls}" text-anchor="{anchor}"{extra}>{esc(s)}</text>')
        else:
            dy = {'h': 40, 't': 27, 'tb': 27, 's': 22, 'sb': 22, 'm': 21, 'note': 21}.get(cls, 24)
            ts = ''.join(f'<tspan x="{x}" dy="{0 if i == 0 else dy}">{esc(l)}</tspan>' for i, l in enumerate(lines))
            self.add(f'<text x="{x}" y="{y}" class="{cls}" text-anchor="{anchor}"{extra}>{ts}</text>')

    def rect(self, x, y, w, h, cls='box', rx=10, **kw):
        extra = ''.join(f' {k.replace("_", "-")}="{v}"' for k, v in kw.items())
        if cls == 'bound':
            self.used.add('bound')
        if cls == 'hz':
            self.used.add('hazard')
        self.add(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="{cls}"{extra}/>')

    def box(self, x, y, w, h, title, body=None, cls='box', tcls='tb'):
        self.rect(x, y, w, h, cls)
        self.text(x + 16, y + 32, title, tcls)
        if body:
            self.text(x + 16, y + 60, body, 's')

    def raw(self, s):
        self.add(s)

    def arrow(self, pts, kind, label=None, at=None, lw=None):
        """pts: list of (x, y). Orthogonal polyline with arrowhead."""
        self.used.add(kind)
        d = 'M' + ' L'.join(f'{x},{y}' for x, y in pts)
        self.add(f'<path d="{d}" class="a-{kind}" marker-end="url(#m-{kind})"/>')
        if label:
            if at is None:
                (x1, y1), (x2, y2) = pts[0], pts[-1]
                at = ((x1 + x2) / 2, (y1 + y2) / 2 - 16)
            self.label(at[0], at[1], label, kind)

    def biarrow(self, pts, kind, label=None, at=None):
        self.used.add(kind)
        d = 'M' + ' L'.join(f'{x},{y}' for x, y in pts)
        self.add(f'<path d="{d}" class="a-{kind}" marker-end="url(#m-{kind})" marker-start="url(#ms-{kind})"/>')
        if label:
            (x1, y1), (x2, y2) = pts[0], pts[-1]
            at = at or ((x1 + x2) / 2, (y1 + y2) / 2 - 16)
            self.label(at[0], at[1], label, kind)

    def label(self, x, y, s, kind=None):
        lines = s.split('\n')
        w = max(len(l) for l in lines) * 9.6 + 20
        h = 26 + 21 * (len(lines) - 1)
        col = COL.get(kind, '#14213d')
        self.add(f'<rect x="{x - w / 2:.0f}" y="{y - 18}" width="{w:.0f}" height="{h}" rx="6" class="lab"/>')
        ts = ''.join(f'<tspan x="{x:.0f}" dy="{0 if i == 0 else 21}">{esc(l)}</tspan>' for i, l in enumerate(lines))
        self.add(f'<text x="{x:.0f}" y="{y}" text-anchor="middle" style="font-size:16px;font-weight:600;fill:{col}">{ts}</text>')

    def coil(self, cx, cy, w, h, turns=3, gap=10, cls='coil'):
        for i in range(turns):
            o = i * gap
            self.add(f'<rect x="{cx - w / 2 + o}" y="{cy - h / 2 + o}" width="{w - 2 * o}" height="{h - 2 * o}" rx="{18 - min(i * 3, 12)}" class="{cls}"/>')

    def fieldlines(self, cx, cy, rx_list, ry_scale=0.55):
        for r in rx_list:
            self.add(f'<ellipse cx="{cx}" cy="{cy}" rx="{r}" ry="{r * ry_scale:.0f}" class="field"/>')

    # output -----------------------------------------------------------
    def render(self, note=None):
        out = ['<?xml version="1.0" encoding="UTF-8"?>',
               '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900" width="1600" height="900" '
               f'font-family="Inter, Arial, sans-serif">',
               f'  <title>Scene {self.num:02d}: {esc(self.title)}</title>',
               f'  <desc>{esc(self.desc)}</desc>',
               f'  <style>{STYLE}  </style>',
               '  <defs>']
        for k in ('energy', 'signal', 'plain', 'crypto', 'admin'):
            out.append(f'    <marker id="m-{k}" viewBox="0 0 12 12" refX="11" refY="6" markerWidth="5" markerHeight="5" orient="auto"><path d="M0,0 L12,6 L0,12 Z" class="c-{k}"/></marker>')
            out.append(f'    <marker id="ms-{k}" viewBox="0 0 12 12" refX="1" refY="6" markerWidth="5" markerHeight="5" orient="auto"><path d="M12,0 L0,6 L12,12 Z" class="c-{k}"/></marker>')
        out.append('  </defs>')
        out.append('  <rect class="bg" width="1600" height="900"/>')
        out.append(f'  <text x="60" y="50" class="k">{esc(self.kicker)}</text>')
        out.append(f'  <text x="60" y="96" style="font-size:40px;font-weight:800;fill:#0f172a;letter-spacing:-0.5px">{esc(self.title)}</text>')
        if self.sub:
            out.append(f'  <text x="60" y="132" style="font-size:20px;fill:#475569">{esc(self.sub)}</text>')
        frames = sorted({f for f, _ in self.parts})
        for fr in frames:
            body = '\n    '.join(s for f, s in self.parts if f == fr)
            if fr == 0:
                out.append('  <g>\n    ' + body + '\n  </g>')
            else:
                out.append(f'  <g data-f="{fr}">\n    ' + body + '\n  </g>')
        # legend
        x = 60
        y = 866
        out.append('  <g class="legend">')
        out.append('    <line x1="60" y1="832" x2="1540" y2="832" stroke="#e2e8f0" stroke-width="2"/>')
        for k in ('energy', 'signal', 'plain', 'crypto', 'admin', 'hazard', 'bound'):
            if k not in self.used:
                continue
            if k in ('hazard', 'bound'):
                cls = 'hz' if k == 'hazard' else 'bound'
                out.append(f'    <rect x="{x}" y="{y - 14}" width="34" height="18" rx="3" class="{cls}" style="stroke-width:{3 if k == "hazard" else 4}"/>')
            else:
                out.append(f'    <path d="M{x},{y - 5} L{x + 34},{y - 5}" class="a-{k}" marker-end="url(#m-{k})"/>')
            out.append(f'    <text x="{x + 46}" y="{y}" class="s">{esc(LEGEND[k])}</text>')
            x += 46 + len(LEGEND[k]) * 8.6 + 30
        if note:
            out.append(f'    <text x="1540" y="{y}" class="note" text-anchor="end">{esc(note)}</text>')
        out.append('  </g>')
        out.append('</svg>')
        return '\n'.join(out) + '\n'
