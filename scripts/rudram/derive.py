#!/usr/bin/env python3
"""Everything the page build needs that is computed rather than written:

  iast       the IAST of every Devanagari string the pages show — produced here,
             by the one transliterator the checker proves (translit.py), so the
             JavaScript build never transliterates anything itself
  svara      for each unit, the syllables where W1 and W2 mark the accent
             differently (the unit is flagged "svara under review")
  collation  the letter differences between W1 and W2 (classified in
             corrections.json)
  counts     per anuvāka: units, words, च and मे in the proven padaccheda

  python3 scripts/rudram/derive.py            # write rudramchamakam/edition/derived.json
  python3 scripts/rudram/derive.py --check    # fail if it is stale (Validate Content)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import collate  # noqa: E402
from translit import dev2iast  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
ED = os.path.join(ROOT, 'rudramchamakam', 'edition')
OUT = os.path.join(ED, 'derived.json')
DEV = re.compile('[ऀ-ॿ᳐-᳿]')


def load(p):
    with open(p, encoding='utf-8') as f:
        return json.load(f)


def analysis(key):
    p = os.path.join(ED, 'analysis', f'{key[0]}{int(key[1:]):02d}.json')
    if not os.path.exists(p):
        return None
    try:
        return load(p)
    except ValueError:
        sys.exit(f'{os.path.relpath(p, ROOT)} is not valid JSON')


def strings_of(obj, out):
    """Every Devanagari string value inside obj (recursively)."""
    if isinstance(obj, str):
        if DEV.search(obj):
            out.add(obj)
    elif isinstance(obj, list):
        for x in obj:
            strings_of(x, out)
    elif isinstance(obj, dict):
        for k, v in obj.items():
            if k in ('traditional', 'reflection', 'summary', 'note', 'context', 'meaning', 'rule', 'type', 'literal', 'readable'):
                continue          # prose: shown as written, never transliterated
            strings_of(v, out)


def derive():
    T = load(os.path.join(ED, 'text.json'))
    C = load(os.path.join(ED, 'corrections.json'))
    S = load(os.path.join(ED, 'witnesses', 'supplements.json')) if os.path.exists(os.path.join(ED, 'witnesses', 'supplements.json')) else {}
    need = set()
    counts = {}
    for a in T['anuvakas']:
        A = analysis(a['id'])
        for u in a['units']:
            need.add(re.sub(r'\s*\[\d+\]', '', u['samhita']))
        if A:
            strings_of(A['units'], need)
            strings_of(A.get('title', {}), need)
            words = [w for u in A['units'] for w in u['padaccheda']]
            counts[a['id']] = {'units': len(A['units']), 'words': len(words),
                               'ca': words.count('च'), 'me': words.count('मे'),
                               'namah': words.count('नमः')}
    for v in C['variants']:
        need.add(v['reading'])
    for c in C['corrections']:
        need.update([c['from'], c['to']])
    strings_of(S, need)
    need = {re.sub(r'\s*\[\d+\]', '', s) for s in need}
    iast = {s: dev2iast(s).replace('·', '') for s in sorted(need)}
    sv, _ = collate.collate_svara()
    svara = {}
    for x in sv:
        svara.setdefault(x['at'], []).append({'w1': x['w1'], 'w2': x['w2']})
    return {'about': 'Generated by scripts/rudram/derive.py — do not edit.',
            'counts': counts, 'svara': svara, 'collation': collate.collate(), 'iast': iast}


def main():
    text = json.dumps(derive(), ensure_ascii=False, indent=0, sort_keys=True) + '\n'
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != text:
            print('derived.json is stale: run python3 scripts/rudram/derive.py')
            sys.exit(1)
        print('derived.json is current')
        return
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
