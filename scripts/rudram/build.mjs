#!/usr/bin/env node
/**
 * Śrī Rudram — study edition build.
 *
 * ONE source, everything else generated from it:
 *   rudramchamakam/edition/text.json         the Saṃhitā (TS 4.5.1–11, 4.7.1–11), with svara
 *   rudramchamakam/edition/corrections.json  corrections to the base witness, classified variants
 *   rudramchamakam/edition/analysis/*.json   per-unit padaccheda, word table, sandhi, samāsa,
 *                                            vyākaraṇa, translations, Sāyaṇa note, reflection
 *   rudramchamakam/edition/witnesses/        the witnesses, Sāyaṇa's bhāṣya, the supplements
 *   rudramchamakam/edition/derived.json      GENERATED by derive.py: every IAST string, the svara
 *                                            collation, counts (the JS never transliterates)
 *   rudramchamakam/edition/audit.json        GENERATED by audit.py: the previous page audited
 *
 *   node scripts/rudram/build.mjs           write rudramchamakam/index.html, namakam-NN.html,
 *                                           chamakam-NN.html, sources.html
 *   node scripts/rudram/build.mjs --check   CI: fail if any of those is stale
 *
 * Never edit the HTML by hand. Run scripts/rudram/check.py too — it proves the
 * text and every padaccheda (docs/SRI-RUDRAM-EDITION.md).
 *
 * Each unit is set out in the order the edition promises: A the Saṃhitā (with
 * svara; a switch hides the marks), B the padaccheda, C the IAST of both, D the
 * word table, E–G sandhi / samāsa / vyākaraṇa (collapsible), H the translation,
 * I the traditional note after Sāyaṇa and an optional, labelled reflection
 * (collapsible). Unit anchors (#n3-7, #c1-2) never change.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const A = (p) => path.join(ROOT, p);
const DIR = 'rudramchamakam';
const ED = `${DIR}/edition`;
const SITE = 'https://paddyspeaks.com';
const CHECK = process.argv.includes('--check');
const readJSON = (p) => JSON.parse(fs.readFileSync(A(p), 'utf8'));

const T = readJSON(`${ED}/text.json`);
const LOG = readJSON(`${ED}/corrections.json`);
const DER = readJSON(`${ED}/derived.json`);
const SAY = readJSON(`${ED}/witnesses/sayana.json`);
const SUPP = readJSON(`${ED}/witnesses/supplements.json`);
const AUD = fs.existsSync(A(`${ED}/audit.json`)) ? readJSON(`${ED}/audit.json`) : null;
const W1 = readJSON(`${ED}/witnesses/W1-panchati.json`);
const AN = new Map();
for (const a of T.anuvakas) {
  const p = `${ED}/analysis/${a.id[0]}${a.id.slice(1).padStart(2, '0')}.json`;
  if (fs.existsSync(A(p))) AN.set(a.id, readJSON(p));
}
const hashOf = (p) => crypto.createHash('sha256').update(fs.readFileSync(A(p))).digest('hex').slice(0, 10);
const CSS_HASH = hashOf(`${ED}/edition.css`);
const JS_HASH = hashOf(`${ED}/reader.js`);

/* ---------- helpers ---------- */
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const DIGITS = '०१२३४५६७८९';
const devNum = (n) => String(n).replace(/\d/g, (d) => DIGITS[d]);
const pad2 = (n) => String(n).padStart(2, '0');
const PARTS = {
  namakam: { name: 'Namakam', dev: 'नमकम्', ts: '4.5', en: 'The salutations', key: 'N' },
  chamakam: { name: 'Chamakam', dev: 'चमकम्', ts: '4.7', en: 'The petitions', key: 'C' },
};
const ORD = ['प्रथमः', 'द्वितीयः', 'तृतीयः', 'चतुर्थः', 'पञ्चमः', 'षष्ठः', 'सप्तमः', 'अष्टमः', 'नवमः', 'दशमः', 'एकादशः'];
const ordTitle = (n) => ORD[n - 1].replace(/ः$/, '') + 'ोऽनुवाकः';
const file = (a) => `${a.part}-${pad2(a.n)}.html`;
const url = (a) => `/${DIR}/${file(a)}`;
const uid = (a, u) => `${a.id[0].toLowerCase()}${a.n}-${u.n}`;
const ushow = (a, u) => `${PARTS[a.part].name} ${a.n}.${u.n}`;
const stripAcc = (s) => s.replace(/[॒॑‌‍]/g, '');
const noPm = (s) => s.replace(/\s*\[\d+\]/g, '');
const missingIAST = new Set();
function iast(dev) {
  const k = noPm(dev);
  if (k in DER.iast) return DER.iast[k];
  missingIAST.add(k);
  return '';
}
const iastLine = (s) => esc(iast(s).replace(/\s*(\|\|?)\s*/g, ' $1 ').trim());
const ORN = '<p class="orn" aria-hidden="true"><span>✲</span></p>';

/** The Saṃhitā, accented and plain, with pañcāśat marks set small. */
function samhitaHTML(s) {
  const pm = (t) => esc(t).replace(/\s*\[(\d+)\]/g, (m, n) => ` <span class="pm" title="pañcāśat ${n}: end of the ${n}th fifty-word division of the prapāṭhaka">[${n}]</span>`);
  return `<span class="sv-acc">${pm(s)}</span><span class="sv-plain">${pm(stripAcc(s))}</span>`;
}

