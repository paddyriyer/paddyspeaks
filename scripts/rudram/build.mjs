/* ---------- one unit ---------- */
function section(cls, title, inner, opts = '') {
  return `<details class="an ${cls}"${opts}><summary><span class="an-t">${title}</span></summary><div class="an-b">${inner}</div></details>`;
}
const isRefrain = (w) => w === 'च' || w === 'मे' || w === 'नमः';
const padaWords = (ws, part) => ws.map((w) => `<span class="pw${part === 'chamakam' && isRefrain(w) ? ' rf' : ''}">${esc(w)}</span>`).join(' <span class="psep" aria-hidden="true">·</span> ');
const padaWordsI = (ws) => ws.map((w) => `<span class="pw">${esc(iast(w))}</span>`).join(' <span class="psep" aria-hidden="true">·</span> ');
const KINDLABEL = { ṛk: 'Ṛk', yajus: 'Yajus', group: 'Sense-group' };
const unitKind = (a, u) => (a.id === 'N11' && u.n === a.units.length ? 'Yajus' : KINDLABEL[a.unit_kind]);
const FLAGLABEL = { uncertain: 'Uncertain', variant: 'Reading', svara: 'Svara', interpretation: 'Interpretation' };

function unitHTML(a, u, e, prev, next, i) {
  const id = uid(a, u);
  const show = ushow(a, u);
  const navs = `<nav class="v-nav" aria-label="Unit ${esc(show)}">${prev ? `<a href="#${uid(a, prev)}" rel="prev" aria-label="Previous unit">‹</a>` : '<span aria-hidden="true">‹</span>'}${next ? `<a href="#${uid(a, next)}" rel="next" aria-label="Next unit">›</a>` : '<span aria-hidden="true">›</span>'}</nav>`;
  const copyTxt = noPm(u.samhita);
  let h = `<section class="verse" id="${id}" data-id="${esc(`${a.n}.${u.n}`)}" data-i="${i}" aria-labelledby="${id}-h">
<header class="v-head"><h3 class="v-num" id="${id}-h"><a href="#${id}"><span class="vn-l">${esc(PARTS[a.part].name)}</span> ${a.n}.${u.n}</a></h3><span class="v-meta">${esc(unitKind(a, u))} · TS ${esc(a.ts)}</span><span class="v-tools"><button type="button" class="copy" data-copy="${esc(copyTxt)}" aria-label="Copy the Sanskrit of ${esc(show)}">Copy</button>${navs}</span></header>`;
  // A. the Saṃhitā
  h += `<div class="v-text"><p class="lbl">Saṃhitā <span>· as recited, with svara</span></p><p class="v-sa" lang="sa">${samhitaHTML(u.samhita)}</p></div>`;
  // flags that belong to the text
  const notes = [];
  const sv = DER.svara[`${a.id}.${u.n}`];
  if (sv) notes.push(`<p class="flag sv"><b>Svara under review:</b> the two accented witnesses mark ${sv.length === 1 ? 'one syllable' : `${sv.length} syllables`} of this unit differently. The marks shown are W1’s; see <a href="/${DIR}/sources.html#svara">Sources</a>.</p>`);
  for (const c of LOG.corrections.filter((x) => x.at === `${a.id}.${u.n}`)) {
    notes.push(`<p class="flag vr"><b>Corrected:</b> <span lang="sa">${esc(c.from)}</span> → <span lang="sa">${esc(c.to)}</span> — ${esc(c.reason)}</p>`);
  }
  for (const v of LOG.variants.filter((x) => x.at === `${a.id}.${u.n}` && x.class !== 'orthographic')) {
    notes.push(`<p class="flag vr"><b>Reading checked:</b> <span lang="sa">${esc(v.reading)}</span> — ${esc(v.note)}</p>`);
  }
  if (!e) {
    return h + notes.join('') + `<p class="v-iast" lang="sa-Latn">${iastLine(noPm(u.samhita))}</p><p class="pending">Padaccheda, word meanings, grammar and translation for this unit are in preparation.</p></section>`;
  }
  // B. padaccheda
  h += `<div class="v-pada"><p class="lbl">Padaccheda <span>· the words separated (a learner’s word division; the traditional pada-pāṭha is not given)</span></p>
<p class="pada-sa" lang="sa">${padaWords(e.padaccheda, a.part)}</p></div>`;
  // C. IAST
  h += `<div class="v-pada"><p class="lbl">IAST</p><p class="v-iast" lang="sa-Latn">${iastLine(noPm(u.samhita))}</p><p class="pada-iast" lang="sa-Latn">${padaWordsI(e.padaccheda)}</p></div>`;
  h += notes.join('');
  // D. word by word
  h += `<div class="v-words"><p class="lbl">Word by word <span>· ${e.words.length} words</span></p><ol class="wl">${e.words.map((w) => `<li><span class="w-sa"><span class="w-d" lang="sa">${esc(w.w)}</span><span class="w-i" lang="sa-Latn">${esc(iast(w.w))}</span></span><span class="w-en">${esc(w.meaning)}${w.context ? `<span class="w-c">${esc(w.context)}</span>` : ''}</span><span class="w-g">${esc(w.gram)}${w.base ? ` <span class="w-b">· <span lang="sa">${esc(w.base)}</span></span>` : ''}</span></li>`).join('')}</ol></div>`;
  // E–G. analysis
  let an = '';
  {
    let s = '';
    if (e.sandhi?.length) {
      s += `<ul class="cards">${e.sandhi.map((x) => `<li><p class="c-h"><span class="c-sa" lang="sa">${esc(x.joined)}</span> <span class="c-i" lang="sa-Latn">${esc(iast(x.joined))}</span> <span class="arr" aria-hidden="true">→</span> <span class="c-sa" lang="sa">${esc(x.split.join(' + '))}</span></p><p class="c-tag">${esc(x.type)}</p><p>${esc(x.rule)}</p></li>`).join('')}</ul>`;
    } else s += `<p class="none">No junction in this unit needs comment.</p>`;
    if (e.sandhi_exceptions?.length) {
      s += `<p class="c-tag">Junctions outside the general rules</p><ul class="plain">${e.sandhi_exceptions.map((x) => `<li><span lang="sa">${esc(e.padaccheda[x.after])} · ${esc(e.padaccheda[x.after + 1] || '')}</span> — <i>${esc(x.kind)}</i>: ${esc(x.note)}</li>`).join('')}</ul>`;
    }
    an += section('an-sandhi', 'Sandhi &amp; sandhi-viccheda', s);
  }
  an += section('an-samasa', 'Samāsa &amp; samāsa-vigraha', e.samasa?.length
    ? `<ul class="cards">${e.samasa.map((x) => `<li><p class="c-h"><span class="c-sa" lang="sa">${esc(x.word)}</span> <span class="c-i" lang="sa-Latn">${esc(iast(x.word))}</span></p><p class="c-tag">${esc(x.type)}</p><dl class="kv"><dt>Members</dt><dd lang="sa">${esc(x.members.join(' + '))}</dd><dt>Vigraha</dt><dd><span lang="sa">${esc(x.vigraha)}</span> <span class="c-i" lang="sa-Latn">${esc(iast(x.vigraha))}</span></dd><dt>Meaning</dt><dd>${esc(x.meaning)}</dd></dl></li>`).join('')}</ul>`
    : `<p class="none">No compound in this unit; every word is a simple word.</p>`);
  an += section('an-morph', 'Vyākaraṇa', e.vyakarana?.length
    ? `<ul class="cards">${e.vyakarana.map((f) => `<li><p class="c-h"><span class="c-sa" lang="sa">${esc(f.word)}</span> <span class="c-i" lang="sa-Latn">${esc(iast(f.word))}</span></p><p>${esc(f.note)}</p></li>`).join('')}</ul>`
    : `<p class="none">The word table gives the grammar of every word; nothing further needs comment.</p>`);
  h += `<div class="v-an" aria-label="Analysis of ${esc(show)}">${an}</div>`;
  // H. translation
  h += `<div class="v-tr"><p class="lbl">Translation</p><p class="tr-lit"><span class="tr-k">Literal</span>${esc(e.translation.literal)}</p><p class="tr-read"><span class="tr-k">In readable English</span>${esc(e.translation.readable)}</p></div>`;
  for (const f of e.flags || []) h += `<p class="flag"><b>${esc(FLAGLABEL[f.kind] || f.kind)}:</b> ${esc(f.note)}</p>`;
  // I. interpretation
  let cm = `<div class="cm"><p class="cm-k traditional">Traditional interpretation · after Sāyaṇa</p><p>${esc(e.traditional)}</p></div>`;
  if (e.reflection) cm += `<div class="cm"><p class="cm-k reflection">Contemplative reflection · modern, not a translation</p><p>${esc(e.reflection)}</p></div>`;
  h += `<div class="v-an">${section('an-comm', 'Interpretation', cm)}</div>`;
  return h + `</section>`;
}

