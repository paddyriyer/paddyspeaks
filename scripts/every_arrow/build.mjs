function words(s) { return (s.replace(/&[a-z#0-9]+;/gi, ' ').match(/[A-Za-z0-9À-ɏ’'-]+/g) || []).length; }
/* A tiny tokenizer: walk tags, keep a stack, count text by layer. */
function countWords(src) {
  const main = src.slice(src.indexOf('<main id="main">'), src.indexOf('</main>'));
  const VOID = new Set(['br', 'img', 'input', 'meta', 'link', 'hr', 'source', 'wbr', 'col']);
  const SKIP = new Set(['script', 'style', 'svg', 'canvas', 'button']);
  const stack = [];
  let full = 0, exec = 0;
  const re = /<(\/?)([a-zA-Z][\w-]*)([^>]*?)(\/?)>|<!--[\s\S]*?-->|([^<]+)/g;
  let m;
  while ((m = re.exec(main))) {
    if (m[5] !== undefined) {
      if (stack.some((f) => f.skip)) continue;
      const w = words(m[5]);
      if (!stack.some((f) => f.noFull)) full += w;
      if (stack.some((f) => f.x) && !stack.some((f) => f.noExec)) exec += w;
      continue;
    }
    if (!m[2]) continue;
    const tag = m[2].toLowerCase();
    if (m[1]) { for (let i = stack.length - 1; i >= 0; i--) if (stack[i].tag === tag) { stack.length = i; break; } continue; }
    if (VOID.has(tag) || m[4]) continue;
    const cls = (/class="([^"]*)"/.exec(m[3]) || [, ''])[1].split(/\s+/);
    const has = (c) => cls.includes(c);
    const f = { tag,
      skip: SKIP.has(tag),
      /* the full path reads prose, briefs and figure lessons; not collapsed notes, not fallbacks shown only without JS */
      noFull: tag === 'details' || (has('fig-static') && !has('fig-static--always')) || has('fig-how') || has('fig-foot') || has('fig-live'),
      x: has('x'),
      /* the executive path reads briefs, chapter arcs and evidence, the thesis, and the six questions — not the reference tables */
      noExec: has('fig-static') || tag === 'details' || has('kit-review') || tag === 'table' };
    if (has('kit-sec') && !/id="north"/.test(m[3])) f.noExec = true;
    stack.push(f);
  }
  return { full, exec };
}
