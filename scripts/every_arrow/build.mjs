/**
 * Every Arrow Is a Decision — build and check, both editions.
 *
 * EDITION 3 is archived at articles/every-arrow/edition-3.html and built by the code
 * in this file (steps 1–7 below). EDITION 4, the live essay at
 * articles/every-arrow-is-a-decision.html, is built by edition4.mjs, which this file
 * runs last — so one command covers both.
 *
 *   node scripts/every_arrow/build.mjs            write: regenerate everything below
 *   node scripts/every_arrow/build.mjs --check    CI: fail if anything is stale or inconsistent
 *   EA_DEPS=/dir/with/node_modules node scripts/every_arrow/build.mjs --pdf
 *                                                 also render the printable PDF (needs playwright)
 *
 * What it does, in order:
 *   1. articles/every-arrow/northstar.js — the subset of the Command Center's synthetic
 *      Northstar dataset (privacy-command-center/v10/data.js) that the essay reads. ONE dataset
 *      for both experiences: the essay never types a Northstar number.
 *   2. Every static fallback in the essay (<div … data-static="X">…</div><!-- /static:X -->):
 *      the no-JS, print and PDF version of each figure, rendered from the SAME data, model
 *      and trail engine the interactive figures use (data.js, model.js, trails.js).
 *   3. The Sources list, from sources.js — and a check that every inline citation
 *      (data-src) has an entry and every entry is cited.
 *   4. Counts and reading times (chapters, scenes, figures, full and executive path), stamped
 *      into every data-ea span, the JSON-LD, article_metadata.json, the /articles/ deck card
 *      and the homepage feature — so they agree everywhere.
 *   5. ?v=<hash> on the essay's own CSS/JS links, so new HTML never meets an old script.
 *   6. With --pdf: the printable edition (articles/every-arrow/every-arrow-is-a-decision.pdf)
 *      and pdf.json (page count + a hash of the source it was rendered from). --check fails
 *      when the PDF is older than its source.
 */
